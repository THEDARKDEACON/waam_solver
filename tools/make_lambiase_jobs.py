"""Write the 24 Yanala/Andreucci/Lambiase 2026 bead jobs (IJAMT 145:4999, Table 4).

Model = jobs/examples/bead_park_measured.yaml (honest energy split, Goldak
volume fixed to the torch); process inputs from the paper:
ER70S-6 Ø1.0 mm, Sw = 171.4 mm/s, Ar + 18 % CO2, CV MIG WELD 303 C,
plate 150 x 30 x 3.3 mm, P = measured mean of V(t)I(t).
Mean current is not published: 195 A is estimated from the Ø1.0 mm ER70S-6
melting rate at 10.3 m/min (it only sets arc pressure / J x B / stick-out
heating; heat input is eta * P).
"""
import copy, pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
T4 = [  # run, P kW, v mm/min, SOD mm, H, W, CS area, contact L, dilution %
 (1, 2.9, 300, 8, 5.0, 6.3, 33.0, 8.0, 25), (2, 2.9, 450, 8, 4.6, 5.0, 24.5, 6.3, 20),
 (3, 2.9, 600, 8, 3.9, 4.5, 19.5, 6.5, 22), (4, 2.9, 750, 8, 3.8, 3.9, 16.5, 6.0, 22),
 (5, 3.3, 300, 8, 4.5, 7.7, 38.0, 10.5, 35), (6, 3.3, 450, 8, 3.5, 6.1, 24.0, 8.0, 25),
 (7, 3.3, 600, 8, 3.1, 5.4, 18.8, 7.8, 35), (8, 3.3, 750, 8, 3.0, 4.3, 15.5, 6.3, 30),
 (9, 3.5, 300, 8, 4.3, 9.0, 41.0, 11.5, 40), (10, 3.5, 450, 8, 3.6, 6.0, 28.0, 9.5, 25),
 (11, 3.5, 600, 8, 3.0, 5.5, 20.0, 8.0, 35), (12, 3.5, 750, 8, 2.8, 4.4, 16.0, 7.0, 31),
 (13, 2.9, 300, 12, 5.5, 6.0, 33.0, 5.8, 14), (14, 2.9, 450, 12, 4.7, 4.5, 21.0, 5.7, 20),
 (15, 2.9, 600, 12, 4.0, 4.0, 18.0, 6.0, 18), (16, 2.9, 750, 12, 3.8, 3.7, 15.0, 5.5, 20),
 (17, 3.3, 300, 12, 4.5, 7.5, 36.0, 10.5, 22), (18, 3.3, 450, 12, 3.5, 5.8, 24.0, 8.0, 25),
 (19, 3.3, 600, 12, 3.2, 5.0, 18.5, 7.5, 35), (20, 3.3, 750, 12, 3.0, 4.2, 15.0, 7.0, 30),
 (21, 3.5, 300, 12, 4.2, 8.5, 38.5, 10.5, 30), (22, 3.5, 450, 12, 3.5, 5.7, 26.0, 7.0, 28),
 (23, 3.5, 600, 12, 3.0, 4.8, 19.0, 7.0, 34), (24, 3.5, 750, 12, 2.8, 4.3, 15.0, 5.8, 30),
]
I_EST = 195.0

def main():
    base = yaml.safe_load((ROOT / "jobs/examples/bead_park_measured.yaml").read_text())
    out = ROOT / "jobs/examples/lambiase2026"; out.mkdir(exist_ok=True)
    for run, P, v, sod, H, W, A, CL, dil in T4:
        j = copy.deepcopy(base)
        j["simulation"]["domain_mm"] = [80, 36, 16]
        j["plate"] = {"thickness_mm": 3.3, "size_mm": [70, 30]}
        j["torch_path_csv"] = "jobs/paths/lambiase_bead.csv"
        globular = P < 3.0
        pr = j["process"]
        for k in ("pulse_frequency_hz", "pulse_peak_A", "pulse_base_A", "pulse_peak_ms", "arc_slope_ohm"):
            pr.pop(k, None)
        pr.update(mean_power_W=P * 1000.0, current_A=I_EST, current_rms_A=I_EST,
                  voltage_V=round(P * 1000.0 / I_EST, 2), travel_speed_mm_s=v / 60.0,
                  wire_feed_m_min=round(171.4 * 60 / 1000, 3), wire_diameter_mm=1.0,
                  ctwd_mm=float(sod), stickout_mm=float(sod),
                  transfer_mode="globular" if globular else "spray",
                  droplet_length_mm=2.2 if globular else 0.7)
        p = dil / 100.0 * H / (1.0 - dil / 100.0)   # penetration from dilution = p/(h+p)
        j["reference"] = {
            "citation_doi": "10.1007/s00170-026-18642-0",
            "source": f"yanala_andreucci_lambiase_2026_table4_run{run}",
            "material_match": True, "experimental_wire": "ER70S-6_1.0mm",
            "awaiting_measurement": False, "gate": "lambiase_section",
            "bead_height_mm": H, "bead_width_mm": W, "contact_length_mm": CL,
            "pool_width_mm": CL, "pool_depth_mm": round(p, 2), "cs_area_mm2": A,
            "dilution_pct": dil, "power_kW": P, "travel_mm_min": v, "sod_mm": sod,
            "gas": "Ar+18%CO2", "current_note": "mean current not published; 195 A estimated",
        }
        (out / f"run{run:02d}.yaml").write_text(
            f"# Yanala, Andreucci & Lambiase 2026 (IJAMT 145:4999) Table 4 run {run}: "
            f"P {P} kW, v {v} mm/min, SOD {sod} mm. Generated by tools/make_lambiase_jobs.py.\n"
            + yaml.safe_dump(j, sort_keys=False))
    print("wrote", len(T4), "jobs to", out)

if __name__ == "__main__":
    main()
