"""Turn measured beads (docs/validation/data/own_beads/own_beads.csv) into twin jobs.

One row per bead (repeats as separate rows with the same bead_id). Inputs are the
logged means of U(t)·I(t), I(t) and the set wire feed / travel / CTWD; outputs are
cross-section width, height, penetration (and area if measured). Jobs go to
jobs/examples/own_beads/<bead_id>.yaml with the mean of the repeats as reference
and the repeat spread recorded, so a pre-registered test can use it as scatter.

Model = jobs/examples/bead_park_measured.yaml (same physics as the Lambiase test);
domain 80 × 36 × 16 mm, 70 × 30 mm plate, straight path x 10 → 70 at y 18.
"""
from __future__ import annotations

import copy
import csv
import pathlib
import statistics as st
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
CSV = ROOT / "docs/validation/data/own_beads/own_beads.csv"
OUT = ROOT / "jobs/examples/own_beads"
NUM = ("mean_power_W", "current_mean_A", "current_rms_A", "voltage_mean_V", "wire_feed_m_min",
       "wire_diameter_mm", "travel_mm_min", "ctwd_mm", "plate_thickness_mm",
       "width_mm", "height_mm", "penetration_mm", "area_mm2")


def _f(x: str):
    x = (x or "").strip()
    return float(x) if x else None


def main(csv_path: pathlib.Path = CSV) -> None:
    rows = [r for r in csv.DictReader(csv_path.open()) if (r.get("bead_id") or "").strip()]
    if not rows:
        sys.exit(f"no beads in {csv_path} yet")
    beads: dict[str, list[dict]] = {}
    for r in rows:
        beads.setdefault(r["bead_id"].strip(), []).append({**r, **{k: _f(r.get(k)) for k in NUM}})
    base = yaml.safe_load((ROOT / "jobs/examples/bead_park_measured.yaml").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    for bid, reps in beads.items():
        def mean(k):
            v = [r[k] for r in reps if r[k] is not None]
            return st.mean(v) if v else None

        def sd(k):
            v = [r[k] for r in reps if r[k] is not None]
            return st.stdev(v) if len(v) > 1 else None

        r0 = reps[0]
        P, I, Irms, V = mean("mean_power_W"), mean("current_mean_A"), mean("current_rms_A"), mean("voltage_mean_V")
        if P is None and I and V:
            P = I * V
        j = copy.deepcopy(base)
        j["simulation"]["domain_mm"] = [80, 36, 16]
        j["plate"] = {"thickness_mm": mean("plate_thickness_mm") or 6.0, "size_mm": [70, 30]}
        j["torch_path_csv"] = "jobs/paths/lambiase_bead.csv"
        pr = j["process"]
        for k in ("pulse_frequency_hz", "pulse_peak_A", "pulse_base_A", "pulse_peak_ms", "arc_slope_ohm"):
            pr.pop(k, None)
        mode = (r0.get("transfer_mode") or "auto").strip() or "auto"
        pr.update(mean_power_W=P, current_A=I, current_rms_A=Irms or I,
                  voltage_V=round(P / I, 2) if (P and I) else V,
                  travel_speed_mm_s=mean("travel_mm_min") / 60.0,
                  wire_feed_m_min=mean("wire_feed_m_min"), wire_diameter_mm=mean("wire_diameter_mm"),
                  ctwd_mm=mean("ctwd_mm"), stickout_mm=mean("ctwd_mm"), transfer_mode=mode)
        ref = {"source": f"own_bead_{bid}", "material_match": True, "awaiting_measurement": False,
               "gate": "own_bead_section", "n_repeats": len(reps), "gas": r0.get("gas", "")}
        for key, col in (("bead_width_mm", "width_mm"), ("bead_height_mm", "height_mm"),
                         ("pool_depth_mm", "penetration_mm"), ("cs_area_mm2", "area_mm2")):
            m = mean(col)
            if m is not None:
                ref[key] = round(m, 3)
                if sd(col) is not None:
                    ref[key.replace("_mm2", "").replace("_mm", "") + "_sd"] = round(sd(col), 3)
        # fusion width at the plate face is compared with the bead width here
        if "bead_width_mm" in ref:
            ref["pool_width_mm"] = ref["bead_width_mm"]
        j["reference"] = ref
        (OUT / f"{bid}.yaml").write_text(
            f"# Own bead {bid} ({len(reps)} repeat(s)). Generated by tools/make_own_bead_jobs.py.\n"
            + yaml.safe_dump(j, sort_keys=False))
    print(f"wrote {len(beads)} jobs to {OUT}")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else CSV)
